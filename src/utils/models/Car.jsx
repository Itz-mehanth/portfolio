/*
Model generated by https://github.com/pmndrs/gltfjsx. Two modes:
- path: eases along a road path between districts (Skill Town's selection).
- drive: an arcade car driven with the keyboard or the joystick.
*/

import React, { useRef, useEffect } from 'react'
import { useGLTF, Outlines } from '@react-three/drei'
import * as THREE from 'three'
import { useFrame, useThree } from '@react-three/fiber'

// Driving feel (units are world units and seconds).
const MAX_FORWARD = 6.2
const MAX_REVERSE = 2.4
const ACCEL = 5.5
const BRAKE = 11
const HANDBRAKE = 16
const COAST_DRAG = 1.6        // speed lost per second when off the throttle
const WHEELBASE = 0.85
const MAX_STEER = 0.6         // radians at standstill; less at speed
const CAR_RADIUS = 0.34
const GRAVITY = 20

// Chase camera.
const CAM_DISTANCE = 3.3
const CAM_HEIGHT = 1.55
const CAM_FOLLOW = 5          // position damping
const CAM_TURN = 3.5          // how quickly the camera swings behind the car

// Reused every frame, never reallocated.
const forward = new THREE.Vector3()
const camGoal = new THREE.Vector3()
const lookGoal = new THREE.Vector3()
const PATH_FORWARD = new THREE.Vector3(-1, 0, 0)
const pathQuat = new THREE.Quaternion()

const approach = (value, target, step) => (value < target ? Math.min(target, value + step) : Math.max(target, value - step))

// One toon-shaded, outlined part of the model.
function Part({ geometry, material, ...rest }) {
  return (
    <mesh castShadow receiveShadow geometry={geometry} {...rest}>
      <meshToonMaterial color={material ? material.color : 'white'} />
      <Outlines thickness={0.9} color="black" />
    </mesh>
  )
}

export default function Car({
  path,
  onReachEnd,
  driveMode = false,
  keysRef,
  colliders = [],
  groundAt = () => 0,
  spawn,
  spawnYaw = 0,
  position,
  ...props
}) {
  const { nodes, materials } = useGLTF('/models/car.glb')
  const characterRef = useRef()
  const bodyRef = useRef()
  const tRef = useRef(0)
  const directionRef = useRef(1)
  const { camera } = useThree()

  // Drive state
  const drive = useRef({ speed: 0, yaw: 0, steer: 0, vy: 0, falling: false, camYaw: 0, pitch: 0, roll: 0, look: new THREE.Vector3() })
  const spawnPos = useRef(spawn ? spawn.clone() : new THREE.Vector3(0, 0, 0))
  // The model's wheels hang below its origin; measured once, then added to every height.
  const liftRef = useRef(null)

  const respawn = () => {
    const car = characterRef.current
    const s = drive.current
    car.position.copy(spawnPos.current)
    car.position.y = (groundAt(car.position.x, car.position.z) ?? spawnPos.current.y) + liftRef.current
    Object.assign(s, { speed: 0, steer: 0, vy: 0, falling: false, yaw: spawnYaw, camYaw: spawnYaw, pitch: 0, roll: 0 })
  }

  useFrame((_, rawDelta) => {
    const car = characterRef.current
    if (!car) return
    const delta = Math.min(rawDelta, 1 / 20)    // no tunnelling after a stalled frame
    if (liftRef.current === null) {
      const box = new THREE.Box3().setFromObject(car)
      if (box.isEmpty()) return
      liftRef.current = car.position.y - box.min.y
      car.position.y += liftRef.current
    }
    const lift = liftRef.current

    if (driveMode && keysRef?.current) {
      const keys = keysRef.current
      const s = drive.current
      if (keys.reset) {
        keys.reset = false
        respawn()
      }

      // Inputs: the joystick is analog; keys are full on.
      const throttle = keys.throttle ?? ((keys.forward ? 1 : 0) - (keys.backward ? 1 : 0))
      const steerIn = keys.steer ?? ((keys.left ? 1 : 0) - (keys.right ? 1 : 0))

      // Throttle, brake and reverse: pushing against the motion brakes first.
      if (!s.falling) {
        if (keys.brake) s.speed = approach(s.speed, 0, HANDBRAKE * delta)
        else if (throttle > 0.05) s.speed = s.speed < 0 ? approach(s.speed, 0, BRAKE * delta) : approach(s.speed, MAX_FORWARD * throttle, ACCEL * delta)
        else if (throttle < -0.05) s.speed = s.speed > 0 ? approach(s.speed, 0, BRAKE * delta) : approach(s.speed, -MAX_REVERSE * -throttle, ACCEL * 0.7 * delta)
        else s.speed = approach(s.speed, 0, COAST_DRAG * delta)
      }

      // Steering: the wheels turn smoothly, steer less at speed, and the car only
      // turns while it's rolling (a bicycle model).
      const maxSteer = MAX_STEER / (1 + Math.abs(s.speed) * 0.1)
      s.steer = THREE.MathUtils.damp(s.steer, steerIn * maxSteer, 10, delta)
      const yawRate = (s.speed / WHEELBASE) * Math.tan(s.steer)
      s.yaw += yawRate * delta

      // The model faces -X.
      forward.set(-Math.cos(s.yaw), 0, Math.sin(s.yaw))
      car.position.x += forward.x * s.speed * delta
      car.position.z += forward.z * s.speed * delta

      // Bump into buildings, turbines and tanks: push out and slide along them.
      for (const c of colliders) {
        const dx = car.position.x - c.x
        const dz = car.position.z - c.z
        const dist = Math.hypot(dx, dz)
        const min = c.r + CAR_RADIUS
        if (dist < min && dist > 1e-4) {
          const nx = dx / dist
          const nz = dz / dist
          car.position.x += nx * (min - dist)
          car.position.z += nz * (min - dist)
          const into = (forward.x * nx + forward.z * nz) * Math.sign(s.speed)
          if (into < 0) s.speed *= 1 + into * 0.75     // head-on stops, glancing keeps speed
        }
      }

      // Follow the ground over hills; off the island's edge, fall and respawn.
      const ground = groundAt(car.position.x, car.position.z)
      if (ground === null) s.falling = true
      if (s.falling) {
        // Keeps its momentum over the edge, then drops into the sea.
        s.vy -= GRAVITY * delta
        car.position.y += s.vy * delta
        if (car.position.y < -6) respawn()
      } else {
        s.vy = 0
        car.position.y = THREE.MathUtils.damp(car.position.y, ground + lift, 18, delta)
      }

      // Body: pitch with the slope, lean out of turns.
      const hFront = groundAt(car.position.x + forward.x * 0.35, car.position.z + forward.z * 0.35)
      const hBack = groundAt(car.position.x - forward.x * 0.35, car.position.z - forward.z * 0.35)
      const slope = hFront !== null && hBack !== null ? Math.atan2(hFront - hBack, 0.7) : 0
      s.pitch = THREE.MathUtils.damp(s.pitch, slope, 10, delta)
      s.roll = THREE.MathUtils.damp(s.roll, THREE.MathUtils.clamp(-s.speed * yawRate * 0.025, -0.12, 0.12), 6, delta)
      car.rotation.set(0, s.yaw, 0)
      if (bodyRef.current) bodyRef.current.rotation.set(s.roll, 0, -s.pitch)

      // Chase camera: swings behind the car with a little lag, pulls back with
      // speed, and looks a little ahead of the bonnet.
      s.camYaw = s.yaw + Math.atan2(Math.sin(s.camYaw - s.yaw), Math.cos(s.camYaw - s.yaw)) * Math.exp(-CAM_TURN * delta)
      const full = CAM_DISTANCE + Math.abs(s.speed) * 0.12
      // Walk out from the car toward the camera spot and stop short of any
      // building, so the camera never ends up inside a wall.
      const bx = Math.cos(s.camYaw)
      const bz = -Math.sin(s.camYaw)
      let dist = full
      for (let k = 1; k <= 12; k++) {
        const d = (full * k) / 12
        const px = car.position.x + bx * d
        const pz = car.position.z + bz * d
        if (colliders.some((c) => c.r > 0.25 && Math.hypot(px - c.x, pz - c.z) < c.r + 0.2)) {
          dist = Math.max(1.1, (full * (k - 1)) / 12)
          break
        }
      }
      camGoal.set(
        car.position.x + bx * dist,
        Math.max(car.position.y, 0) + CAM_HEIGHT + Math.abs(s.speed) * 0.04 + (full - dist) * 0.45,
        car.position.z + bz * dist,
      )
      const camGround = groundAt(camGoal.x, camGoal.z)
      if (camGround !== null) camGoal.y = Math.max(camGoal.y, camGround + 0.6)
      camera.position.x = THREE.MathUtils.damp(camera.position.x, camGoal.x, CAM_FOLLOW, delta)
      camera.position.y = THREE.MathUtils.damp(camera.position.y, camGoal.y, CAM_FOLLOW, delta)
      camera.position.z = THREE.MathUtils.damp(camera.position.z, camGoal.z, CAM_FOLLOW, delta)
      lookGoal.set(car.position.x + forward.x * 1.4, car.position.y + 0.3, car.position.z + forward.z * 1.4)
      s.look.x = THREE.MathUtils.damp(s.look.x, lookGoal.x, 8, delta)
      s.look.y = THREE.MathUtils.damp(s.look.y, lookGoal.y, 8, delta)
      s.look.z = THREE.MathUtils.damp(s.look.z, lookGoal.z, 8, delta)
      camera.lookAt(s.look)
    } else if (path && tRef.current < 1) {
      // Path-following mode: constant cruising speed along the path, eased at both ends.
      const length = path.getLength() || 1
      let nextT = tRef.current + directionRef.current * (delta * 5.5) / length

      if (nextT >= 1) {
        nextT = 1
        directionRef.current = -1
        if (onReachEnd) onReachEnd()
      } else if (nextT <= 0) {
        nextT = 0
        directionRef.current = 1
      }

      const eased = nextT < 0.5 ? 2 * nextT * nextT : 1 - Math.pow(-2 * nextT + 2, 2) / 2
      const point = path.getPointAt(eased)
      car.position.set(point.x, point.y + lift, point.z)

      const tangent = path.getTangentAt(Math.min(Math.max(eased, 0.001), 0.999))
      tangent.y = 0
      tangent.normalize()
      pathQuat.setFromUnitVectors(PATH_FORWARD, tangent)
      car.quaternion.slerp(pathQuat, 0.2)

      tRef.current = nextT
    }
  })

  // Reset position when path changes (only in path mode)
  useEffect(() => {
    if (path && !driveMode) {
      tRef.current = 0
      directionRef.current = 1
    }
  }, [path, driveMode])

  // Entering drive mode: start from where the car stands, camera already behind it.
  useEffect(() => {
    const car = characterRef.current
    if (!car) return
    const s = drive.current
    if (driveMode) {
      const yaw = new THREE.Euler().setFromQuaternion(car.quaternion, 'YXZ').y
      Object.assign(s, { speed: 0, steer: 0, vy: 0, falling: false, yaw, camYaw: yaw, pitch: 0, roll: 0 })
      s.look.copy(car.position)
    } else if (bodyRef.current) {
      bodyRef.current.rotation.set(0, 0, 0)
    }
  }, [driveMode])

  return (
    <group
      scale={0.3}
      ref={characterRef}
      // Re-applied by React when the resting district changes: keep the wheel lift.
      position={position && liftRef.current !== null ? [position[0], position[1] + liftRef.current, position[2]] : position}
      {...props}
      dispose={null}
    >
      <group ref={bodyRef}>
        <group scale={[0.52, 0.288, 0.52]}>
          <Part geometry={nodes.Cube001_1.geometry} material={materials['Material.003']} />
          <Part geometry={nodes.Cube001_2.geometry} material={materials['Material.003']} />
          <Part geometry={nodes.Cube001_3.geometry} material={materials['Material.001']} />
          <Part geometry={nodes.Cube001_4.geometry} material={materials['Material.001']} />
          <Part geometry={nodes.Cube001_5.geometry} material={materials['Material.001']} />
          <Part geometry={nodes.Cube001_6.geometry} material={materials['Material.004']} />
          <Part geometry={nodes.Cube001_7.geometry} material={materials['Material.001']} />

          <group position={[0, 0, 0.017]}>
            <Part geometry={nodes.Cube002_1.geometry} material={materials['Material.003']} />
            <Part geometry={nodes.Cube002_2.geometry} material={materials['Material.001']} />
          </group>
          <group position={[-0.006, 0, 0.402]} rotation={[Math.PI, 0, Math.PI]}>
            <Part geometry={nodes.Cube002_1.geometry} material={materials['Material.003']} />
            <Part geometry={nodes.Cube002_2.geometry} material={materials['Material.001']} />
          </group>
          <group position={[0, 0, 0.402]} rotation={[Math.PI, 0, Math.PI]}>
            <Part geometry={nodes.Cube003_1.geometry} material={materials['Material.003']} />
            <Part geometry={nodes.Cube003_2.geometry} material={materials['Material.001']} />
          </group>
          <group position={[-0.006, 0, 0.017]}>
            <Part geometry={nodes.Cube003_1.geometry} material={materials['Material.003']} />
            <Part geometry={nodes.Cube003_2.geometry} material={materials['Material.001']} />
          </group>

          <Part geometry={nodes.Cube005.geometry} material={materials['Material.001']} />
          <Part geometry={nodes.Cube006.geometry} material={materials['Material.001']} position={[0, -0.498, 0]} />
          <Part geometry={nodes.Cube007.geometry} material={materials['Material.001']} position={[-0.943, -0.227, 0.397]} rotation={[Math.PI, 0, Math.PI]} />

          {/* Wheels */}
          <group position={[1.292, -2.752, -0.873]} rotation={[Math.PI / 2, 0, 0]} scale={[0.434, 0.099, 0.785]}>
            <Part geometry={nodes.Cylinder_1.geometry} material={materials['Material.001']} />
            <Part geometry={nodes.Cylinder_2.geometry} material={materials['Material.002']} />
          </group>
          <group position={[1.292, -2.752, 1.276]} rotation={[Math.PI / 2, 0, Math.PI]} scale={[0.434, 0.099, 0.785]}>
            <Part geometry={nodes.Cylinder_1.geometry} material={materials['Material.001']} />
            <Part geometry={nodes.Cylinder_2.geometry} material={materials['Material.002']} />
          </group>
          <group position={[-2.132, -2.752, -0.873]} rotation={[Math.PI / 2, 0, 0]} scale={[0.434, 0.099, 0.785]}>
            <Part geometry={nodes.Cylinder_1.geometry} material={materials['Material.001']} />
            <Part geometry={nodes.Cylinder_2.geometry} material={materials['Material.002']} />
          </group>
          <group position={[-2.132, -2.752, 1.276]} rotation={[Math.PI / 2, 0, Math.PI]} scale={[0.434, 0.099, 0.785]}>
            <Part geometry={nodes.Cylinder_1.geometry} material={materials['Material.001']} />
            <Part geometry={nodes.Cylinder_2.geometry} material={materials['Material.002']} />
          </group>
        </group>
      </group>
    </group>
  )
}

